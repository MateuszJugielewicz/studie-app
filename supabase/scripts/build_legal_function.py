"""Bundles legal/*.md into supabase/functions/legal/docs.ts so the public pages (privacy policy,
terms, support) can be served without a website. Run after changing anything in legal/."""
import json, os, re

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
LEGAL = os.path.join(ROOT, "legal")
docs = {}
for lang in ["en"] + sorted(d for d in os.listdir(LEGAL) if os.path.isdir(os.path.join(LEGAL, d))):
    folder = LEGAL if lang == "en" else os.path.join(LEGAL, lang)
    for name in sorted(os.listdir(folder)):
        if name.endswith(".md"):
            text = open(os.path.join(folder, name), encoding="utf-8").read()
            text = re.sub(r"<!--.*?-->\s*", "", text, flags=re.S).strip() + "\n"
            docs[f"{lang}/{name[:-3]}"] = text
out = os.path.join(ROOT, "supabase", "functions", "legal", "docs.ts")
with open(out, "w", encoding="utf-8") as f:
    f.write("// Generated by supabase/scripts/build_legal_function.py from legal/. Don't edit by hand.\n")
    f.write("export const DOCS: Record<string, string> = " + json.dumps(docs, ensure_ascii=False, indent=1) + ";\n")
print(f"{out}: {len(docs)} documents")
